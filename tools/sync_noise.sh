#!/usr/bin/env bash
# 从 cn-telemetry-collectors 数据仓库同步 DNS 噪音语料, 生成固件内置头文件。
#
# 语料 = Majestic Million 头部 2000 个域名(按引用子网数排名), 定宽 32B 记录。
# 流行度加权不烧进文件——固件在抽取时用头重分布(p^2.5)选 rank, 文件保持
# 纯粹可审计的有序列表。v0 编译期嵌入(PROGMEM), 随固件 OTA 更新。
#
# 用法: tools/sync_noise.sh   (产物: src/noise_corpus.h, 需提交)
set -euo pipefail
cd "$(dirname "$0")/.."

URL="https://github.com/ichewm/cn-telemetry-collectors/releases/download/list/noise-corpus.bin"
TMP=$(mktemp); trap 'rm -f "$TMP"' EXIT
# 下载优先级: gh API > GitHub raw > Gitee API(私有仓库也可, 凭据运行时取)
if command -v gh >/dev/null 2>&1 && gh release download list --repo ichewm/cn-telemetry-collectors \
     --pattern 'noise-corpus.bin' --output "$TMP" --clobber 2>/dev/null; then
  :
else
  TOK=$(printf 'protocol=https\nhost=gitee.com\n\n' | git credential fill 2>/dev/null | awk -F= '/^password/{print $2}')
  curl -sfL -m 120 "$URL" -o "$TMP" || \
  curl -sf -m 60 "https://gitee.com/api/v5/repos/hewmbj/cn-telemetry-collectors/raw/noise-corpus.bin?ref=dist&access_token=$TOK" -o "$TMP" || \
  { echo '错误: 三个下载通道都失败' >&2; exit 1; }
fi

python3 - "$TMP" <<'EOF'
import sys, datetime
blob = open(sys.argv[1], 'rb').read()
REC = 32
assert len(blob) % REC == 0, f'corpus size {len(blob)} not a multiple of {REC}'
n = len(blob) // REC
doms = []
for i in range(n):
    rec = blob[i*REC:(i+1)*REC]
    d = rec.split(b'\x00', 1)[0].decode()
    assert d and len(d) < REC and ' ' not in d, f'bad record {i}: {d!r}'
    doms.append(d)
assert len(doms) >= 1000, f'corpus too small: {len(doms)}'
today = datetime.date.today().isoformat()
out = []
out.append('// AUTO-GENERATED by tools/sync_noise.sh — DO NOT EDIT BY HAND.')
out.append('// Source: cn-telemetry-collectors rolling release (noise-corpus.bin)')
out.append('// https://github.com/ichewm/cn-telemetry-collectors')
out.append(f'// Synced: {today} | Records: {n} | Fixed width: 32B')
out.append('// DNS-noise corpus for the profile-fog scheduler: rank-ordered popular')
out.append('// domains; the firmware draws ranks head-heavy (p^2.5) at query time.')
out.append('// Regenerate with: tools/sync_noise.sh')
out.append('')
out.append('static const char* const NOISE_DOMAINS[] = {')
for d in doms:
    out.append(f'    "{d}",')
out.append('};')
out.append('static const int NOISE_COUNT = sizeof(NOISE_DOMAINS) / sizeof(NOISE_DOMAINS[0]);')
open('src/noise_corpus.h', 'w').write('\n'.join(out) + '\n')
print(f'src/noise_corpus.h: {n} 条')
EOF
echo "✓ 完成 — 记得提交并重新编译"
