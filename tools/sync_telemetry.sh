#!/usr/bin/env bash
# 从 cn-telemetry-collectors 数据仓库同步遥测采集端清单, 生成固件内置头文件。
#
# 设计决策: v0 采用"编译期嵌入"(PROGMEM 字符串数组)而非设备端远程更新——
# 清单变化缓慢(周更主要是隔离区审校), 跟随固件 OTA 的节奏足够, 设备端零新增
# 更新路径。清单长大后(P6 之后)再考虑 LittleFS 文件 + 远程拉取。
#
# 数据源: 列表仓库 rolling release 的 telemetry.hosts (版本化, 与 dist 分支
# 内容一致)。嵌入字符串而非哈希: 16~50 条的量级下 strcmp 零成本, 且无碰撞
# 风险、dashboard 可展示。
#
# 用法: tools/sync_telemetry.sh   (产物: src/telemetry_list.h, 需提交)
set -euo pipefail
cd "$(dirname "$0")/.."

URL="https://github.com/ichewm/cn-telemetry-collectors/releases/download/list/telemetry.hosts"
TMP=$(mktemp); trap 'rm -f "$TMP"' EXIT
curl -sL -m 60 "$URL" -o "$TMP"

python3 - "$TMP" <<'EOF'
import re, sys, datetime
src = open(sys.argv[1]).read()
domains = sorted(set(re.findall(r'^0\.0\.0\.0 ([a-z0-9.-]+)$', src, re.M)))
assert len(domains) >= 10, f'清单太小({len(domains)}条), 数据源可能损坏'
for d in domains:
    assert re.match(r'^[a-z0-9.-]+\.[a-z]{2,}$', d), f'非法域名: {d}'
today = datetime.date.today().isoformat()
header = (
    '// AUTO-GENERATED by tools/sync_telemetry.sh — DO NOT EDIT BY HAND.\n'
    '// Source: cn-telemetry-collectors rolling release (telemetry.hosts)\n'
    '// https://github.com/ichewm/cn-telemetry-collectors\n'
    f'// Synced: {today} | Entries: {len(domains)}\n'
    '// These are evidence-verified telemetry COLLECTION endpoints. The firmware\n'
    '// answers them with its own IP (graveyard mode): the SDK connects, gets a\n'
    '// 204 No Content from our web server, records a successful upload and stops\n'
    '// retrying — instead of hammering a refused 0.0.0.0 with backoff.\n'
    '// Regenerate with: tools/sync_telemetry.sh\n\n'
    'static const char* const TELEMETRY_DOMAINS[] = {\n'
)
body = '\n'.join('    "' + d + '",' for d in domains)
footer = (
    '\n};\n'
    'static const int TELEMETRY_COUNT = sizeof(TELEMETRY_DOMAINS) / sizeof(TELEMETRY_DOMAINS[0]);\n'
)
open('src/telemetry_list.h', 'w').write(header + body + footer)
print(f'src/telemetry_list.h: {len(domains)} 条目')
EOF
echo "✓ 完成 — 记得提交头文件并重新编译固件"
